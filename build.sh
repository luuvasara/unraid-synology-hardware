#!/bin/bash
# build.sh [version] - build synology-hardware-<version>-x86_64-1.txz on the build host (NEVER on a NAS).
# Written: 2026-10-24. 2026-10-25b: include/*.php linted too. 2026-10-25j: every SynologyHW*.page (tabbed page) linted. 2026-10-25f: js/*.js checked with node --check when node exists. 2026-10-25: version defaults to the .plg's &version; (and must match it), the
# .plg's &md5; entity is updated from the built txz, page/scripts are syntax-checked.
# Dir modes are forced (build umask is not trusted) and the archive root is verified.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
PLG=$HERE/synology-hardware.plg
PLGVER=$(sed -n 's/^ *<!ENTITY version *"\([^"]*\)">.*/\1/p' "$PLG")
VER=${1:-$PLGVER}
[ "$VER" = "$PLGVER" ] || { echo "FATAL: version $VER != synology-hardware.plg &version; $PLGVER (bump the .plg first)"; exit 1; }
OUT=$HERE/packages; mkdir -p "$OUT"
PKG=$OUT/synology-hardware-$VER-x86_64-1.txz
S=usr/local/emhttp/plugins/synology-hardware
ST=$(mktemp -d); trap 'rm -rf "$ST"' EXIT
cp -a "$HERE/src/." "$ST/"
find "$ST" -type d -exec chmod 755 {} +
find "$ST" -type f -exec chmod 644 {} +
chmod 755 "$ST"/etc/rc.d/rc.synology-hardware "$ST"/etc/rc.d/rc6.d/K05synology-hardware "$ST"/$S/scripts/synohw-*
chmod 644 "$ST"/$S/scripts/synohw-lib.sh
# every script must parse; the page's PHP must lint (php is on the build host, not needed on the NAS)
for f in "$ST"/etc/rc.d/rc.synology-hardware "$ST"/etc/rc.d/rc6.d/K05synology-hardware "$ST"/$S/scripts/synohw-*; do bash -n "$f"; done
if command -v php >/dev/null; then
  for f in "$ST"/$S/SynologyHW*.page "$ST"/$S/include/*.php; do
    LINT=$(php -l "$f" 2>&1) || { echo "FATAL: php -l failed: $LINT"; exit 1; }
  done
else echo "warning: php not found, page not linted"; fi
if command -v node >/dev/null; then for f in "$ST"/$S/js/*.js; do node --check "$f" || { echo "FATAL: node --check $f"; exit 1; }; done
else echo "warning: node not found, page script not syntax-checked"; fi
rm -f "$PKG" "$PKG.md5"
tar -C "$ST" --owner=root --group=root --numeric-owner --sort=name -cJf "$PKG" .
ROOT=$(tar -tJvf "$PKG" | sed -n 1p)   # sed reads all input: head -1 + pipefail = SIGPIPE (exit 141)
echo "archive root entry: $ROOT"
case "$(awk '{print $1}' <<<"$ROOT")" in drwxr-xr-x) ;; *) echo "FATAL: archive root is not drwxr-xr-x"; rm -f "$PKG"; exit 1 ;; esac
tar -tJvf "$PKG" | awk '$1 ~ /^d/ && $1 != "drwxr-xr-x" {bad=1; print "FATAL dir mode: " $0} END{exit bad}'
tar -tJvf "$PKG" | awk '$2 != "0/0" {bad=1; print "FATAL owner: " $0} END{exit bad}'
(cd "$OUT" && md5sum "$(basename "$PKG")" >"$(basename "$PKG").md5")
MD5=$(cut -d' ' -f1 "$PKG.md5")
# write the MD5 into the .plg (entity used by <MD5>&md5;</MD5> and the pre-install payload check)
sed -i "s|^\( *<!ENTITY md5 *\)\"[^\"]*\">|\1\"$MD5\">|" "$PLG"
grep -q "<!ENTITY md5 *\"$MD5\">" "$PLG" || { echo "FATAL: could not write md5 into $PLG"; exit 1; }
python3 -c 'import sys,xml.dom.minidom as m; m.parse(sys.argv[1])' "$PLG" || { echo "FATAL: $PLG is not well-formed XML"; exit 1; }
# CHANGELOG.md mirrors the .plg's <CHANGES> (the .plg is the source; Unraid shows it on the Plugins page)
{ echo "# Changelog"; echo; echo "Generated by build.sh from the <CHANGES> block of synology-hardware.plg; edit the .plg, not this file."; echo
  sed -n '/^<CHANGES>/,/^<\/CHANGES>/p' "$PLG" | sed '1d;$d' | sed -e 's/^###/## /' -e 's/&lt;/</g; s/&gt;/>/g; s/&amp;/\&/g'
} >"$HERE/CHANGELOG.md"
echo "built $PKG"; cat "$PKG.md5"; echo "synology-hardware.plg: &md5; = $MD5"
